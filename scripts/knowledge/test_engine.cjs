const assert=require('node:assert/strict');
const E=require('../../templates/knowledge-engine.js');
const comp={group:'物理',conditions:[{kind:'item',id:'emblem'}],optional_emblems:['optional'],augments:[{id:'a'}],stages:[{level:4,units:['a','b','c','d']},{level:6,units:['a','b','e','f','g','h']},{level:6,units:['h','g','f','e','b','a']}]};
const state={group:'全部',emblems:[],augments:[],emblemOnly:false};
assert.equal(E.gaps(comp,state).length,1);
assert.equal(E.gaps(comp,{...state,emblems:['emblem']}).length,0);
assert(E.passes(comp,state));
assert(!E.passes(comp,{...state,augments:['a','missing']}));
assert(E.passes(comp,{...state,emblems:['missing','optional'],emblemOnly:true}));
assert.equal(E.boards(comp,4,['e']).length,0);
assert.equal(E.boards(comp,6,['e']).length,1,'future search independent of current matches; duplicates removed');
const rows=[{units:['a','b','c']},{units:['a','b','d']},{units:['a','e','d']}];
assert.deepEqual(E.fill(rows,['a'],[]).frequency,[['b',2],['d',2],['c',1],['e',1]]);
assert.deepEqual(E.fill(rows,['a'],['b']).frequency,[['c',1],['d',1]]);
assert.equal(E.fill(rows,['a'],['c','d']).matches.length,0,'incompatible choices never fabricate a combination');
const gear=[{items:['x','x','y']},{items:['x','y','z']}];
assert.deepEqual(E.equipment(gear,['x','x']).map(x=>x.missing),[['y']]);
assert.deepEqual(E.equipment(gear,['x','y','z']).map(x=>x.missing),[[]]);
assert.equal(E.equipment(gear,['absent']).length,0);
console.log('PASS: source-level matching, independent future routes, conditional gates, filtered frequency, multiset gear completion.');
